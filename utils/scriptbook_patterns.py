# ==================== SE（音效）标记模式 ====================

SE_PATTERNS = [
    r'^[SEＳＥ][:：]',           # SE: 或 SE：
    r'^[SEＳＥ]\s',              # SE 开头
    r'^\s*[SEＳＥ]\s*[:：]?\s*', # 可选空格
    r'^【効果音[:：]',     # 【効果音：xxx】
    r'^【効果音：',        # 【効果音：xxx】
    r'^（ＳＥ[:：]',       # （ＳＥ：xxx）
]

# ==================== 标记与指示模式 ====================

# 方向指示（如 #正面　距離近く）
DIRECTION_PATTERN = r'^#[^\n]+$'

# 角色名标记（如 【まどか】）
CHARACTER_PATTERN = r'^【[^】]+】\s*$'

# 章节标题（如 《トラック１　エルフの子作り日》）
CHAPTER_TITLE_PATTERN = r'^《[^》]+》'

# 位置指示（如 【右・中】、【右・中→右・近】）
POSITION_PATTERN = r'^【[左右中正遠近・→]+】\s*$'

# 位置标记组合模式（如 【右耳・近距離】）
POSITION_COMPLEX_PATTERN = r'^【(?:右耳|左耳|右|左|中央|正面|遠距離|近距離|中距離)[・→・]+[^】]*】\s*$'

# 移动指示（如 【移動：右耳・近距離】）
MOVE_PATTERN = r'^【移動[:：]'

# 声音方式指示（如 【囁き】、【通常】、【大声】）
VOICE_STYLE_PATTERN = r'^【(?:囁き|通常|大声|小声|吐息)\s*】\s*$'

# 射精标记（如 ★射精、【射精】）
EJACULATION_PATTERN = r'^(★|☆).*射精|^【射精】'

# 演技提示（行首的 （xxx））
ACTING_HINT_PATTERN = r'^（[^）]+）\s*$'

# 台词缩进标记（行首有空格的台词）
DIALOGUE_INDENT_PATTERN = r'^\s+[^【《\(（#SE]'

# ==================== 音轨标记模式 ====================

# 基础音轨标记（translate.py 使用，较宽泛）
TRACK_PATTERN = r'^(【トラック[０-９0-9]+[：：]?[^\]]*】|Tr\.?\s*\d+[\.：:;\s]|TR\d+[\s\.：:;]|Tr\d+[\s\.：:;]|トラック\s*[０-９0-9]+[\s\.：：;]|[Tt]rack\s*\d+[\s\.：:]|[①②③④⑤⑥⑦⑧⑨⑩]?【[^】]+?\d+文字】)'

# === scriptbook_utils 使用的额外/精确音轨模式 ===

# ■トラック０１、◆トラック１： 等方块/菱形前缀格式（排除〆结束标记）
TRACK_MARK_PATTERN = r'^[■◆]《?[^■◆《]*トラック[０-９0-9]+[^〆]*$'

# 【01.、【1. 格式
TRACK_BRACKET_NUM_PATTERN = r'^【\d+\.\s*'

# トラック１．、トラック2. 格式
TRACK_DOT_PATTERN = r'^トラック[０-９0-9]+[\.．]'

# ☆★数字标记（如 ☆１、☆２、★１）
STAR_TRACK_PATTERN = r'^[☆★]\s*[０-９0-9]+$'

# ☆プロローグ、☆エピローグ 等
STAR_CHAPTER_PATTERN = r'^[☆★]\s*(プロローグ|エピローグ|おまけ|特典)'

# 🔶１章、🔷２章 等
CHAPTER_TRACK_PATTERN = r'^[🔶🔷]\s*[０-９0-9]+章'

# 带圆圈的数字
CIRCLED_NUMBERS = '①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳'

# Tr./Track 格式（支持带圆圈数字）
TR_DOT_PATTERN = r'^[■◆□●○]?(?:[Tr\.トラックTrack]+\s*)[０-９0-9' + CIRCLED_NUMBERS + r']+'

# 🔷①、🔷② 等子音轨标记
SUB_TRACK_PATTERN = r'^[🔷🔶]\s*[' + CIRCLED_NUMBERS + r']+'

# 广播剧/电视剧型章节标记（第一話ここまで）
DRAMA_EPISODE_PATTERN = r'^第[一二三四五六七八九十百千]+話ここまで'
DRAMA_OP_PATTERN = r'^OP$'
DRAMA_OP_END_PATTERN = r'^OP明け$'

# ▼track数字 / ▼数字 格式
TRACK_TRIANGLE_PATTERN = r'^▼\s*(?:track|Track|TRACK)?\s*[０-９0-9]+'

